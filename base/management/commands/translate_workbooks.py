"""``manage.py translate_workbooks [--app <id>] [--check]``: each app's ``WORKBOOK.en.md`` (spec §4.5).

The WORKBOOK is written in Spanish (it is the specification); its English version is generated by
the Claude API from its user part (``base.catalog.user_part``) and versioned next to it, headed by
``<!-- generated from WORKBOOK.md sha256:<hash> -->``. The hash is the user part's, so editing
«Para quien lo mantiene» never asks for a new translation, and an unchanged hash costs no call.

Run by hand by whoever edits a WORKBOOK, never in CI nor in the build: the ``anthropic`` client is a
development dependency, its key ``ANTHROPIC_API_KEY`` lives in the local ``.env`` (or the
environment) and the model is ``settings.WORKBOOK_TRANSLATION_MODEL``. Without the key, a module to
translate stops the command before any call, naming the key; an up-to-date one needs none.
``--check`` never reaches the network nor needs the key: it fails listing the modules whose
``WORKBOOK.en.md`` exists and is out of date (a missing one is no error).
"""

import re
from pathlib import Path

import decouple
from django.conf import settings
from django.core.management.base import BaseCommand, CommandError

from base import catalog

#: The fixed instructions of every translation (spec §4.5).
INSTRUCTIONS = """\
You translate the customer documentation of an app of ERPlora, a point-of-sale and back-office \
platform for small businesses in Spain, from Spanish into English.

The user message is a Markdown document. Reply with its English translation and nothing else: no \
preface, no notes, no code fence around it.

- Translate the prose, the headings, the text of tables and lists, and the alt text of images.
- Keep the Markdown structure exactly as it is: heading levels, lists, tables, emphasis, quotes \
and blank lines.
- Leave untouched: inline code and code blocks, identifiers such as `demo.item.created` or \
`inventory.manage`, URLs and external links, and image paths (`docs/img/...`).
- Translate the date placeholders of a pattern, even inside inline code: `AAAA` is `YYYY` and \
`aaaa` is `yyyy` (`OS-AAAAMMDD-NNNN` is `OS-YYYYMMDD-NNNN`, `DD/MM/AAAA` is `DD/MM/YYYY`); the \
rest of the pattern (`MM`, `DD`, `NNNN`, `hh:mm`) stays as it is.
- Rewrite every in-page link `(#...)` to point at its translated heading: the heading in lowercase, \
punctuation removed and spaces as hyphens (`## How to use it` is `#how-to-use-it`).
- Translate the labels of the app quoted with «...» as the English app shows them, in double quotes.
"""
#: Long WORKBOOKs come back whole: streamed, so the request never times out.
MAX_TOKENS = 64000
#: The Claude API key: without it no call is made.
API_KEY = "ANTHROPIC_API_KEY"
_IMAGE_PATH_RE = re.compile(r"docs/img/[^\s)\"'>]+")
#: A pattern still carrying the Spanish year placeholder (`OS-AAAAMMDD-NNNN`, `DD/MM/AAAA`).
_SPANISH_DATE_RE = re.compile(r"[\w/:-]*(?:AAAA|aaaa)[\w/:-]*")


def translate(source: str) -> str:
    """The English translation of ``source`` (a Spanish user part), in one call to the Claude API."""
    try:
        import anthropic
    except ModuleNotFoundError as error:
        raise CommandError(
            "translate_workbooks needs the anthropic client, a development dependency: run `uv sync`."
        ) from error
    # Read as every setting (environment, then this checkout's .env) and handed to the client, which
    # only looks at the environment: python-decouple exports nothing.
    api_key = decouple.config(API_KEY, default="")
    if not api_key:
        raise CommandError(
            f"translate_workbooks needs {API_KEY} to call the Claude API: set it in this checkout's .env "
            "(or the environment) and run it again. translate_workbooks --check needs no key."
        )
    try:
        with anthropic.Anthropic(api_key=api_key).messages.stream(
            model=settings.WORKBOOK_TRANSLATION_MODEL,
            max_tokens=MAX_TOKENS,
            system=INSTRUCTIONS,
            messages=[{"role": "user", "content": source}],
        ) as stream:
            message = stream.get_final_message()
    except anthropic.APIError as error:
        raise CommandError(
            f"The Claude API failed, nothing written: {error}"
        ) from error
    if message.stop_reason != "end_turn":
        raise CommandError(
            f"The Claude API stopped with {message.stop_reason!r} instead of finishing: nothing written."
        )
    return "".join(block.text for block in message.content if block.type == "text")


class Command(BaseCommand):
    help = "Generate each app's WORKBOOK.en.md (the modules' and base's) from the user part of its WORKBOOK.md (Claude API)."

    def add_arguments(self, parser):
        parser.add_argument(
            "--app", help="Only this app (its label, e.g. inventory or base)."
        )
        parser.add_argument(
            "--check",
            action="store_true",
            help="Fail when a WORKBOOK.en.md is out of date; never reaches the network.",
        )

    def handle(self, *args, app: str | None = None, check: bool = False, **options):
        # The modules and base (the platform's WORKBOOK): base is no module of the store, but its
        # WORKBOOK.en.md is generated and checked like theirs.
        configs = catalog.workbook_configs()
        if app is not None:
            known = ", ".join(sorted(config.label for config in configs))
            configs = [config for config in configs if config.label == app]
            if not configs:
                raise CommandError(f"No app {app!r} with a WORKBOOK to translate; the apps are: {known}.")
        if check:
            stale = catalog.stale_translations(configs)
            if stale:
                commands = "; ".join(
                    f"translate_workbooks --app {label}" for label in stale
                )
                raise CommandError(
                    f"Out of date WORKBOOK.en.md: {', '.join(stale)}. Run {commands}."
                )
            self.stdout.write("Every WORKBOOK.en.md is up to date.")
            return
        for config in configs:
            if (Path(config.path) / catalog.WORKBOOK).is_file():
                self._translate(config)

    def _translate(self, config) -> None:
        try:
            state = catalog.workbook_translation(config)
        except catalog.WorkbookError as error:
            raise CommandError(
                f"{config.label}: {catalog.WORKBOOK}: {error}"
            ) from error
        if state.state == "current":
            self.stdout.write(f"{config.label}: up to date.")
            return
        english = translate(state.source).strip() + "\n"
        lost = sorted(
            set(_IMAGE_PATH_RE.findall(state.source))
            - set(_IMAGE_PATH_RE.findall(english))
        )
        if lost:
            raise CommandError(
                f"{config.label}: the translation changed the image paths {', '.join(lost)}: nothing written."
            )
        spanish_dates = sorted(set(_SPANISH_DATE_RE.findall(english)))
        if spanish_dates:
            raise CommandError(
                f"{config.label}: the translation kept the Spanish date placeholders {', '.join(spanish_dates)}: nothing written."
            )
        try:
            catalog.check_anchors(english)
        except catalog.WorkbookError as error:
            raise CommandError(
                f"{config.label}: the translation {error} Nothing written."
            ) from error
        header = catalog.en_header(catalog.source_hash(state.source))
        state.en_path.write_text(f"{header}\n\n{english}", encoding="utf-8")
        self.stdout.write(
            f"{config.label}: wrote {catalog.WORKBOOK_EN}; review the diff before committing it."
        )
